//! Printer geometry Amber can slice for.
//!
//! Build area and pixel grid come from manufacturer figures collected in the
//! UVtools printer profiles (`PrusaSlicer/printer` in
//! <https://github.com/sn4k3/UVtools>). Amber does not include that program.
//! Lift speeds in those notes are millimetres per minute and are stored here
//! as millimetres per second. A Photon Workshop v516 file is written only when
//! the profile says `FILEVERSION_516`. Every machine can also be saved as `.sl1`.

#[derive(Clone, Copy, Debug)]
pub struct PrinterProfile {
    pub id: &'static str,
    pub name: &'static str,
    pub vendor: &'static str,
    pub res_x: u32,
    pub res_y: u32,
    pub size_x: f32,
    pub size_y: f32,
    pub size_z: f32,
    pub pixel_x_um: f32,
    pub pixel_y_um: f32,
    /// Community profile mirror. The Photon M3 Max keeps its own orientation.
    pub mirror_x: bool,
    pub mirror_y: bool,
    /// Suffix the printer itself reads.
    pub printer_extension: &'static str,
    pub file_version: u32,
    pub native_photon: bool,
    pub format_name: &'static str,
    pub light_off_s: f32,
    pub lift_mm: f32,
    pub lift_speed: f32,
    pub retract_speed: f32,
}

