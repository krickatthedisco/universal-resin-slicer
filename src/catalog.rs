#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn m3_max_is_the_known_panel_and_ids_are_unique() {
        let mut ids = std::collections::HashSet::new();
        for p in PRINTERS {
            assert!(ids.insert(p.id), "duplicate {}", p.id);
            assert!(p.res_x > 1 && p.res_y > 1);
            assert!(p.size_x > 1.0 && p.size_y > 1.0 && p.size_z > 1.0);
            let wx = p.res_x as f32 * p.pixel_x_um / 1000.0;
            let hy = p.res_y as f32 * p.pixel_y_um / 1000.0;
            assert!(
                (wx - p.size_x).abs() < 0.05,
                "{} x {} vs {}",
                p.name,
                wx,
                p.size_x
            );
            assert!(
                (hy - p.size_y).abs() < 0.05,
                "{} y {} vs {}",
                p.name,
                hy,
                p.size_y
            );
            if p.native_photon {
                assert_eq!(p.file_version, 516, "{}", p.name);
                assert!((p.pixel_x_um - p.pixel_y_um).abs() < 0.05, "{}", p.name);
            }
        }
        let m = find("anycubic-photon-m3-max").unwrap();
        assert_eq!(m.res_x, 6480);
        assert_eq!(m.res_y, 3600);
        assert!((m.pixel_x_um - 46.0).abs() < 0.01);
        assert!((m.size_z - 300.0).abs() < 0.01);
        assert!(m.native_photon);
        assert_eq!(m.printer_extension, "pm3m");
        assert!(PRINTERS.len() > 100);
    }
}
